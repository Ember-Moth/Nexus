from collections.abc import Callable
from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from .schemas import CredentialView, DeploymentView, ModelView, Page, UpstreamView, Visibility

type Cursor = tuple[datetime, UUID] | None


class Access(Protocol):
    async def administrator(self, token: str) -> UUID: ...
    async def visibility(
        self, token: str, organization_id: UUID | None, project_id: UUID | None, key_id: UUID | None
    ) -> Visibility: ...


class Cipher(Protocol):
    def supports(self, version: int) -> bool: ...
    @property
    def versions(self) -> frozenset[int]: ...
    def encrypt(self, secret: str, upstream_id: UUID, credential_id: UUID) -> tuple[int, bytes]: ...


class CatalogStore(Protocol):
    async def lock(self) -> None: ...
    async def audit(
        self, actor_id: UUID, action: str, resource_id: UUID, details: dict | None = None
    ) -> None: ...
    async def list_models(
        self, allowed: frozenset[UUID] | None, versions: frozenset[int], limit: int, cursor: Cursor
    ) -> Page[ModelView]: ...
    async def model(self, model_id: UUID, versions: frozenset[int]) -> ModelView | None: ...
    async def known_models(self, ids: frozenset[UUID]) -> frozenset[UUID]: ...
    async def create_model(self, values: dict, versions: frozenset[int]) -> ModelView: ...
    async def update_model(
        self, model_id: UUID, values: dict, versions: frozenset[int]
    ) -> ModelView: ...
    async def active_protocols(self, model_id: UUID) -> frozenset[str]: ...
    async def upstreams(self, limit: int, cursor: Cursor) -> Page[UpstreamView]: ...
    async def upstream(self, upstream_id: UUID) -> UpstreamView | None: ...
    async def create_upstream(self, values: dict) -> UpstreamView: ...
    async def update_upstream(self, upstream_id: UUID, values: dict) -> UpstreamView: ...
    async def credentials(
        self, upstream_id: UUID, limit: int, cursor: Cursor
    ) -> Page[CredentialView]: ...
    async def credential(self, upstream_id: UUID, credential_id: UUID) -> CredentialView | None: ...
    async def create_credential(
        self, credential_id: UUID, upstream_id: UUID, name: str, key_version: int, ciphertext: bytes
    ) -> CredentialView: ...
    async def revoke_credential(self, upstream_id: UUID, credential_id: UUID) -> CredentialView: ...
    async def deployments(
        self,
        versions: frozenset[int],
        model_id: UUID | None,
        upstream_id: UUID | None,
        limit: int,
        cursor: Cursor,
    ) -> Page[DeploymentView]: ...
    async def deployment(
        self, deployment_id: UUID, versions: frozenset[int]
    ) -> DeploymentView | None: ...
    async def create_deployment(self, values: dict, versions: frozenset[int]) -> DeploymentView: ...
    async def update_deployment(
        self, deployment_id: UUID, values: dict, versions: frozenset[int]
    ) -> DeploymentView: ...


type Transactions = Callable[[], AbstractAsyncContextManager[CatalogStore]]
