type Cursor = tuple[datetime, UUID] | None


@dataclass(frozen=True)
class Actor:
    user: UserView
    session_id: UUID
    platform_roles: frozenset[str]


class AuthLimits(Protocol):
    async def allow(self, subject: str, peer: str) -> bool: ...


class Passwords(Protocol):
    def hash(self, password: str) -> str: ...

    def verify(self, password_hash: str | None, password: str) -> bool: ...


class Administrators(Protocol):
    async def lock_bootstrap(self) -> None: ...

    async def first_admin(self) -> tuple[UUID, str] | None: ...

    async def login_exists(self, login: str) -> bool: ...

    async def create(self, user_id: UUID, login: str, password_hash: str) -> None: ...


class Audit(Protocol):
    async def record_bootstrap(self, user_id: UUID) -> None: ...

    async def record(
        self,
        actor_id: UUID,
        action: str,
        resource_id: UUID,
        *,
        organization_id: UUID | None = None,
        details: dict | None = None,
    ) -> None: ...


class Directory(Protocol):
    async def now(self) -> datetime: ...
    async def roles(self, user_id: UUID) -> PlatformRolesView | None: ...
    async def replace_roles(self, user_id: UUID, roles: list[str]) -> PlatformRolesView: ...
    async def other_administrators(self, user_id: UUID) -> int: ...
    async def pending_organizations(self, limit: int) -> list[OrganizationCreated]: ...
    async def account_ready(
        self, event_id: UUID, organization_id: UUID, account_id: UUID
    ) -> None: ...
    async def credentials(self, login: str) -> tuple[UserView, str | None] | None: ...
    async def user(self, user_id: UUID, *, lock: bool = False) -> UserView | None: ...
    async def password_matches(self, user_id: UUID, password_hash: str) -> bool: ...
    async def create_user(self, login: str, password_hash: str | None = None) -> UserView: ...
    async def personal_org_id(self, user_id: UUID) -> UUID: ...
    async def issue_invitation(
        self, org_id: UUID, login: str, role: str, invited_by: UUID, digest: str, expires: datetime
    ) -> InvitationView: ...
    async def cancel_pending_invitations(self, org_id: UUID, login: str) -> None: ...
    async def invitation_org(self, digest: str) -> UUID | None: ...
    async def redeem_invitation(
        self, org_id: UUID, digest: str, user: UserView
    ) -> tuple[MemberView, bool]: ...
    async def invitations(
        self, org_id: UUID, limit: int, cursor: Cursor
    ) -> Page[InvitationView]: ...
    async def revoke_invitation(self, org_id: UUID, invitation_id: UUID) -> UUID | None: ...
    async def users(self, limit: int, cursor: Cursor) -> Page[UserView]: ...
    async def actor(self, digest: str) -> Actor | None: ...
    async def create_session(self, user_id: UUID, digest: str, expires_at: datetime) -> None: ...
    async def revoke_session(self, digest: str) -> UUID | None: ...
    async def setup_user(self, digest: str) -> UUID | None: ...
    async def issue_setup(self, user_id: UUID, digest: str, expires_at: datetime) -> None: ...
    async def replace_password(self, user_id: UUID, password_hash: str) -> None: ...
    async def consume_setup(self, digest: str, user_id: UUID, password_hash: str) -> bool: ...
    async def organization(
        self, organization_id: UUID, *, lock: bool = False
    ) -> OrganizationView | None: ...
    async def organizations(
        self, user_id: UUID | None, limit: int, cursor: Cursor
    ) -> Page[OrganizationView]: ...
    async def create_organization(self, name: str, owner_id: UUID) -> OrganizationView: ...
    async def update_organization(
        self, organization_id: UUID, name: str | None, status: str | None
    ) -> OrganizationView: ...
    async def membership_for_user(
        self, organization_id: UUID, user_id: UUID
    ) -> MemberView | None: ...
    async def membership(self, organization_id: UUID, membership_id: UUID) -> MemberView | None: ...
    async def my_memberships(self, user_id: UUID) -> list[MemberView]: ...
    async def members(
        self, organization_id: UUID, limit: int, cursor: Cursor
    ) -> Page[MemberListItem]: ...
    async def create_member(
        self, organization_id: UUID, user_id: UUID, role: str
    ) -> MemberView: ...
    async def update_member(
        self, organization_id: UUID, membership_id: UUID, role: str, status: str
    ) -> MemberView: ...
    async def active_owner_count(self, organization_id: UUID) -> int: ...


